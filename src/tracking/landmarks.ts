/** Index of the landmark on the opposite side of the body (used by mirror mode). */
export const POSE_MIRROR_INDEX: readonly number[] = (() => {
  const out: number[] = [];
  for (let i = 0; i < POSE_LANDMARK_NAMES.length; i++) {
    const name = POSE_LANDMARK_NAMES[i];
    let swapped: string;
    if (name.startsWith('left_')) swapped = 'right_' + name.slice(5);
    else if (name.startsWith('right_')) swapped = 'left_' + name.slice(6);
    else if (name === 'mouth_left') swapped = 'mouth_right';
    else if (name === 'mouth_right') swapped = 'mouth_left';
    else swapped = name;
    out.push(POSE_LANDMARK_NAMES.indexOf(swapped as PoseLandmarkName));
  }
  return out;
})();

